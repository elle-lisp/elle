//! One opcode byte per `LirInstr` variant.
//!
//! docs/impl/image/measurements.md
//!
//! Its own file because the enum has 89 variants, and the prototype's node
//! carries the variant as a byte: a backend that matches on 89 opcodes
//! branches as the shipped translator does, where a coarser encoding would
//! flatter the read.

use elle::lir::LirInstr;

/// The opcode byte: one per `LirInstr` variant, in declaration order. The match
/// is exhaustive, so a new variant is reported here rather than encoded as
/// something else.
pub fn opcode(i: &LirInstr) -> u8 {
    match i {
        LirInstr::Const { .. } => 0,
        LirInstr::ValueConst { .. } => 1,
        LirInstr::MaterializeConst { .. } => 2,
        LirInstr::LoadLocal { .. } => 3,
        LirInstr::StoreLocal { .. } => 4,
        LirInstr::StoreLocalRefcounted { .. } => 5,
        LirInstr::LoadCapture { .. } => 6,
        LirInstr::LoadCaptureRaw { .. } => 7,
        LirInstr::StoreCapture { .. } => 8,
        LirInstr::MakeClosure { .. } => 9,
        LirInstr::LoadSelf { .. } => 10,
        LirInstr::Call { .. } => 11,
        LirInstr::SuspendingCall { .. } => 12,
        LirInstr::TailCall { .. } => 13,
        LirInstr::List { .. } => 14,
        LirInstr::MakeArrayMut { .. } => 15,
        LirInstr::First { .. } => 16,
        LirInstr::Rest { .. } => 17,
        LirInstr::BinOp { .. } => 18,
        LirInstr::UnaryOp { .. } => 19,
        LirInstr::Convert { .. } => 20,
        LirInstr::Compare { .. } => 21,
        LirInstr::IsNil { .. } => 22,
        LirInstr::IsPair { .. } => 23,
        LirInstr::IsArray { .. } => 24,
        LirInstr::IsArrayMut { .. } => 25,
        LirInstr::IsStruct { .. } => 26,
        LirInstr::IsStructMut { .. } => 27,
        LirInstr::IsSet { .. } => 28,
        LirInstr::IsSetMut { .. } => 29,
        LirInstr::ArrayMutLen { .. } => 30,
        LirInstr::MakeCaptureCell { .. } => 31,
        LirInstr::LoadCaptureCell { .. } => 32,
        LirInstr::StoreCaptureCell { .. } => 33,
        LirInstr::MatchFail { .. } => 34,
        LirInstr::FirstDestructure { .. } => 35,
        LirInstr::RestDestructure { .. } => 36,
        LirInstr::ArrayMutRefDestructure { .. } => 37,
        LirInstr::ArrayMutSliceFrom { .. } => 38,
        LirInstr::StructGetOrNil { .. } => 39,
        LirInstr::StructGetDestructure { .. } => 40,
        LirInstr::StructRest { .. } => 41,
        LirInstr::FirstOrNil { .. } => 42,
        LirInstr::RestOrNil { .. } => 43,
        LirInstr::ArrayMutRefOrNil { .. } => 44,
        LirInstr::LoadResumeValue { .. } => 45,
        LirInstr::Eval { .. } => 46,
        LirInstr::ArrayMutExtend { .. } => 47,
        LirInstr::ArrayMutPush { .. } => 48,
        LirInstr::CallArrayMut { .. } => 49,
        LirInstr::TailCallArrayMut { .. } => 50,
        LirInstr::IncrefRegion { .. } => 51,
        LirInstr::DecrefRegion { .. } => 52,
        LirInstr::DecrefValueRegion { .. } => 53,
        LirInstr::DecrefCellRegion { .. } => 54,
        LirInstr::IncrefValueRegion { .. } => 55,
        LirInstr::AdoptRegion { .. } => 56,
        LirInstr::AdoptCellRegion { .. } => 57,
        LirInstr::FreeRegionGroup { .. } => 58,
        LirInstr::AdoptIntoActivation { .. } => 59,
        LirInstr::AssertRegionMatches { .. } => 60,
        LirInstr::JoinRegion { .. } => 61,
        LirInstr::PushParamFrame { .. } => 62,
        LirInstr::PopParamFrame => 63,
        LirInstr::CheckSignalBound { .. } => 64,
        LirInstr::IsEmpty { .. } => 65,
        LirInstr::IsBool { .. } => 66,
        LirInstr::IsInt { .. } => 67,
        LirInstr::IsFloat { .. } => 68,
        LirInstr::IsString { .. } => 69,
        LirInstr::IsKeyword { .. } => 70,
        LirInstr::IsSymbolCheck { .. } => 71,
        LirInstr::IsBytes { .. } => 72,
        LirInstr::IsBox { .. } => 73,
        LirInstr::IsClosure { .. } => 74,
        LirInstr::IsFiber { .. } => 75,
        LirInstr::TypeOf { .. } => 76,
        LirInstr::Length { .. } => 77,
        LirInstr::Get { .. } => 78,
        LirInstr::Put { .. } => 79,
        LirInstr::Del { .. } => 80,
        LirInstr::Has { .. } => 81,
        LirInstr::IntrPush { .. } => 82,
        LirInstr::IntrStringPush { .. } => 83,
        LirInstr::IntrBytesPush { .. } => 84,
        LirInstr::Pop { .. } => 85,
        LirInstr::Freeze { .. } => 86,
        LirInstr::Thaw { .. } => 87,
        LirInstr::Identical { .. } => 88,
    }
}
