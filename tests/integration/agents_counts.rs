// audited: 2026-10-25
// The two counts of the generated index: the hand-written indexes, and the rows in them that name a file.
//
// docs/impl/agents-index.md
//
// The counts are what tests/ratchet/agents.lisp reads and its ledger pins.
// The counter-factual: `--check` skipped every hand-written index and said
// nothing, so a directory that never converted read as green, and a row added
// to one moved no number at all.

use std::path::Path;
use std::process::{Command, Output};

use crate::common::{write_fixture, ScratchDir};

fn script() -> std::path::PathBuf {
    std::path::PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("scripts/agents")
}

/// The first line of every index the generator writes.
const MARKER: &str = "Generated by `scripts/agents`. Edit a document, never this index.";

/// `scripts/agents --root ROOT ARGS…`, which must succeed.
fn agents(root: &Path, args: &[&str]) -> Output {
    let out = Command::new(script())
        .args(["--root", root.to_str().expect("utf-8 path")])
        .args(args)
        .output()
        .expect("run scripts/agents");
    assert!(
        out.status.success(),
        "scripts/agents {args:?} failed with {:?}:\n{}{}",
        out.status.code(),
        String::from_utf8_lossy(&out.stdout),
        String::from_utf8_lossy(&out.stderr)
    );
    out
}

fn stdout(out: &Output) -> String {
    String::from_utf8(out.stdout.clone()).expect("utf-8 output")
}

/// A hand-written index whose table holds three rows that name a file, and
/// four lines that look like one and do not.
const INDEX: &str = "# a

Hand-written knowledge about this directory.

| File | Purpose |
|------|---------|
| [x.rs](x.rs) | a link names a file |
| `y.lisp` | a code span with an extension names a file |
| `sub/` | a code span ending in a slash names a directory |
| `io/submit` | a primitive's name is no file |
| `/` | a route is no file |
| plain | a row whose purpose links [z.rs](z.rs) |

A paragraph that links [w.rs](w.rs) is no row.
";

#[test]
fn counts_name_the_hand_written_indexes_and_the_rows_that_name_a_file() {
    let t = ScratchDir::new("agents-counts");
    // The root index is the guide, and neither count reads it.
    write_fixture(t.path(), "AGENTS.md", INDEX);
    write_fixture(t.path(), "a/AGENTS.md", INDEX);
    write_fixture(t.path(), "a/doc.md", "# Doc\n\nA document.\n");
    // A generated index is the generator's, whatever it lists.
    write_fixture(
        t.path(),
        "b/AGENTS.md",
        &format!("# b\n\n{MARKER}\n\n| [x.rs](x.rs) | a row |\n"),
    );
    // A directory that holds no other document still holds a hand-written
    // index. The counter-factual: a count taken over the directories the
    // generator would index skips it, as the generator's own walk does.
    write_fixture(t.path(), "c/AGENTS.md", "# c\n\nKnowledge, and no table.\n");

    assert_eq!(
        stdout(&agents(t.path(), &["--counts"])),
        "hand-written 2\nfile-rows 3\n",
        "a/ and c/ are hand-written, and a/ holds three rows that name a file"
    );
}

#[test]
fn the_counts_read_only_the_files_git_tracks() {
    // The counter-factual: `find` reads every file under the root, so a
    // submodule checked out in one clone and absent from another, or an
    // index nobody committed, reads a different count for one commit.
    let t = ScratchDir::new("agents-tracked");
    write_fixture(t.path(), "a/AGENTS.md", INDEX);
    write_fixture(t.path(), "untracked/AGENTS.md", INDEX);
    for args in [&["init", "-q"][..], &["add", "a/AGENTS.md"][..]] {
        let out = Command::new("git")
            .current_dir(t.path())
            .args(args)
            .output()
            .expect("run git");
        assert!(out.status.success(), "git {args:?} failed");
    }

    assert_eq!(
        stdout(&agents(t.path(), &["--counts"])),
        "hand-written 1\nfile-rows 3\n",
        "the untracked index is in neither count"
    );
}

#[test]
fn check_prints_the_counts_where_it_passes_a_hand_written_index() {
    let t = ScratchDir::new("agents-check-counts");
    write_fixture(t.path(), "a/AGENTS.md", INDEX);
    write_fixture(t.path(), "a/doc.md", "# Doc\n\nA document.\n");

    let out = stdout(&agents(t.path(), &["--check"]));
    assert!(
        out.contains("hand-written 1\nfile-rows 3\n"),
        "--check passes the unconverted directory and says how many remain:\n{out}"
    );
}

#[test]
fn a_write_prints_the_counts_and_leaves_the_root_alone() {
    // The root is the guide. The counter-factual: a tree whose root holds
    // documents and no index gets a generated root index on the first run,
    // and a person's guide is then the generator's to overwrite.
    let t = ScratchDir::new("agents-write-counts");
    write_fixture(t.path(), "top.md", "# Top\n\nA document at the root.\n");
    write_fixture(t.path(), "a/AGENTS.md", INDEX);
    write_fixture(t.path(), "a/doc.md", "# Doc\n\nA document.\n");
    write_fixture(t.path(), "d/doc.md", "# Doc\n\nA document.\n");

    let out = agents(t.path(), &[]);
    let text = stdout(&out);
    assert!(
        text.contains("hand-written 1\nfile-rows 3\n"),
        "a write prints the counts after the count it wrote:\n{text}"
    );
    assert!(
        t.join("d/AGENTS.md").exists(),
        "the generator still writes a directory it owns"
    );
    assert!(
        !t.join("AGENTS.md").exists(),
        "the generator never writes the root index"
    );
}

#[test]
fn a_write_names_no_root_guide_as_skipped() {
    let t = ScratchDir::new("agents-root-guide");
    write_fixture(t.path(), "AGENTS.md", INDEX);
    write_fixture(t.path(), "top.md", "# Top\n\nA document at the root.\n");

    let out = agents(t.path(), &[]);
    let err = String::from_utf8_lossy(&out.stderr);
    assert!(
        !err.contains("skipped ."),
        "the root guide is no unconverted index:\n{err}"
    );
    assert_eq!(
        std::fs::read_to_string(t.join("AGENTS.md")).expect("the guide is there"),
        INDEX,
        "and the run leaves it as it was"
    );
}
