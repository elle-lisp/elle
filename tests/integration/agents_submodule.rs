// audited: 2026-10-23
// No run of scripts/agents writes or checks an index inside a submodule, which is another repository's.
//
// docs/impl/agents-index.md
//
// The counter-factual: the walk took every directory under the root, the
// plugins submodule included. A write left that checkout dirty with indexes
// of this generator's making, and a check failed on indexes the submodule
// keeps by its own rules.

use std::path::Path;
use std::process::{Command, Output};

use crate::common::ScratchDir;

fn script() -> std::path::PathBuf {
    std::path::PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("scripts/agents")
}

/// Write `body` at `rel` under `root`, creating its directories.
fn write(root: &Path, rel: &str, body: &str) {
    let path = root.join(rel);
    std::fs::create_dir_all(path.parent().expect("has a parent")).expect("create fixture dir");
    std::fs::write(&path, body).expect("write fixture file");
}

/// `git ARGS…` in `dir`, which must succeed. Local paths serve as a remote,
/// and every commit names an author, whatever the box's own git config says.
fn git(dir: &Path, args: &[&str]) {
    let out = Command::new("git")
        .current_dir(dir)
        .args([
            "-c",
            "protocol.file.allow=always",
            "-c",
            "user.name=fixture",
            "-c",
            "user.email=fixture@example.invalid",
        ])
        .args(args)
        .output()
        .expect("run git");
    assert!(
        out.status.success(),
        "git {args:?} failed:\n{}",
        String::from_utf8_lossy(&out.stderr)
    );
}

/// A repository whose `sub/` is a submodule holding a document of its own.
fn outer_with_submodule(t: &ScratchDir) -> std::path::PathBuf {
    let inner = t.join("inner");
    write(
        &inner,
        "docs/d.md",
        "# D\n\nA document of the submodule's.\n",
    );
    git(&inner, &["init", "-q"]);
    git(&inner, &["add", "."]);
    git(&inner, &["commit", "-q", "-m", "inner"]);

    let outer = t.join("outer");
    write(&outer, "AGENTS.md", "# guide\n\nWritten by a person.\n");
    write(
        &outer,
        "docs/top.md",
        "# Top\n\nA document of the outer tree's.\n",
    );
    git(&outer, &["init", "-q"]);
    git(
        &outer,
        &[
            "submodule",
            "add",
            "-q",
            inner.to_str().expect("utf-8 path"),
            "sub",
        ],
    );
    git(&outer, &["add", "."]);
    git(&outer, &["commit", "-q", "-m", "outer"]);
    outer
}

fn agents(root: &Path, args: &[&str]) -> Output {
    Command::new(script())
        .args(["--root", root.to_str().expect("utf-8 path")])
        .args(args)
        .output()
        .expect("run scripts/agents")
}

#[test]
fn a_write_leaves_a_submodule_alone() {
    let t = ScratchDir::new("agents-submodule-write");
    let outer = outer_with_submodule(&t);

    let out = agents(&outer, &[]);
    assert!(
        out.status.success(),
        "scripts/agents failed:\n{}",
        String::from_utf8_lossy(&out.stderr)
    );
    assert!(
        outer.join("docs/AGENTS.md").exists(),
        "the outer tree's own directory is indexed"
    );
    assert!(
        !outer.join("sub/docs/AGENTS.md").exists(),
        "the submodule's directory is not"
    );
}

#[test]
fn a_check_reads_no_index_inside_a_submodule() {
    let t = ScratchDir::new("agents-submodule-check");
    let outer = outer_with_submodule(&t);
    assert!(
        agents(&outer, &[]).status.success(),
        "the first write succeeds"
    );
    // An index the submodule keeps, which this generator would not write.
    write(
        &outer,
        "sub/docs/AGENTS.md",
        "# docs\n\nGenerated by `scripts/agents`. Edit a document, never this index.\n\nits own body\n",
    );

    let out = agents(&outer, &["--check"]);
    assert!(
        out.status.success(),
        "--check judges the outer tree alone:\n{}",
        String::from_utf8_lossy(&out.stderr)
    );
}
