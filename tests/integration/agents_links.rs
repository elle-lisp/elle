// audited: 2026-10-23
// Every link a generated index writes leads to a file, in a fixture and in this tree.
//
// docs/impl/agents-index.md
//
// The counter-factual: the generator linked every subdirectory to its
// AGENTS.md, and a directory that holds only sources has none. The prose
// checks read stamped files alone, and a generated index carries no stamp, so
// the dead link stood in the tree with nothing to fail on it.

use std::path::Path;
use std::process::Command;

use crate::common::ScratchDir;

fn repo_root() -> std::path::PathBuf {
    std::path::PathBuf::from(env!("CARGO_MANIFEST_DIR"))
}

/// The first line of every index the generator writes.
const MARKER: &str = "Generated by `scripts/agents`. Edit a document, never this index.";

/// The root guide a fixture holds, so the link up from each index leads to it.
const GUIDE: &str = "# guide\n\nWritten by a person, and never generated.\n";

/// Write `body` at `rel` under `root`, creating its directories.
fn write(root: &Path, rel: &str, body: &str) {
    let path = root.join(rel);
    std::fs::create_dir_all(path.parent().expect("has a parent")).expect("create fixture dir");
    std::fs::write(&path, body).expect("write fixture file");
}

/// The target of every markdown link in `text`, its anchor cut off.
fn link_targets(text: &str) -> Vec<String> {
    text.split("](")
        .skip(1)
        .filter_map(|rest| rest.split_once(')'))
        .map(|(target, _)| target.split('#').next().unwrap_or("").to_string())
        .filter(|target| !target.is_empty() && !target.contains("://"))
        .collect()
}

/// The links in `index`, a file under `dir`, that lead to no file.
fn dead_links(dir: &Path, index: &str) -> Vec<String> {
    link_targets(index)
        .into_iter()
        .filter(|target| !dir.join(target).exists())
        .collect()
}

#[test]
fn an_index_links_a_subdirectory_only_when_it_has_an_index() {
    let t = ScratchDir::new("agents-links");
    write(t.path(), "AGENTS.md", GUIDE);
    write(t.path(), "docs/a.md", "# A\n\nA document.\n");
    write(t.path(), "docs/sub/b.md", "# B\n\nA document below.\n");
    write(
        t.path(),
        "docs/hand/AGENTS.md",
        "# hand\n\nKnowledge, not yet converted.\n",
    );
    write(t.path(), "docs/src/x.rs", "// a source and no document\n");

    let out = Command::new(repo_root().join("scripts/agents"))
        .args(["--root", t.path().to_str().expect("utf-8 path")])
        .output()
        .expect("run scripts/agents");
    assert!(
        out.status.success(),
        "scripts/agents failed:\n{}",
        String::from_utf8_lossy(&out.stderr)
    );

    let index = std::fs::read_to_string(t.join("docs/AGENTS.md")).expect("docs/ is indexed");
    assert!(
        index.contains("](sub/AGENTS.md)") && index.contains("](hand/AGENTS.md)"),
        "a directory with a document, and one with an unconverted index, are linked:\n{index}"
    );
    assert!(
        !index.contains("src/"),
        "a directory of sources alone has no index to link:\n{index}"
    );
    let dead = dead_links(&t.join("docs"), &index);
    assert!(dead.is_empty(), "dead links {dead:?} in:\n{index}");
}

#[test]
fn a_summary_quoted_from_a_child_keeps_its_links_alive() {
    // The trap: the call-out of `mod/overview.md` links `../mod.lisp`, the
    // file beside the directory. Quoted into the parent unchanged, the link
    // climbs out of the parent instead, to a file that is not there.
    let t = ScratchDir::new("agents-summary-links");
    write(t.path(), "AGENTS.md", GUIDE);
    write(t.path(), "lib/top.md", "# Top\n\nA document.\n");
    write(t.path(), "lib/mod.lisp", "# the module\n");
    write(
        t.path(),
        "lib/mod/overview.md",
        "# Mod\n\nThe parts of [the module](../mod.lisp) and [its guide](guide.md).\n",
    );
    write(t.path(), "lib/mod/guide.md", "# Guide\n\nHow to use it.\n");

    let out = Command::new(repo_root().join("scripts/agents"))
        .args(["--root", t.path().to_str().expect("utf-8 path")])
        .output()
        .expect("run scripts/agents");
    assert!(
        out.status.success(),
        "scripts/agents failed:\n{}",
        String::from_utf8_lossy(&out.stderr)
    );
    let index = std::fs::read_to_string(t.join("lib/AGENTS.md")).expect("lib/ is indexed");
    assert!(
        index.contains("The parts of [the module]("),
        "the summary is the child's call-out:\n{index}"
    );
    let dead = dead_links(&t.join("lib"), &index);
    assert!(dead.is_empty(), "dead links {dead:?} in:\n{index}");
}

#[test]
fn every_link_in_a_generated_index_of_this_tree_leads_to_a_file() {
    let root = repo_root();
    let out = Command::new("git")
        .args(["ls-files", "--", "*AGENTS.md"])
        .current_dir(&root)
        .output()
        .expect("git ls-files");
    assert!(out.status.success(), "git ls-files failed");

    let mut dead = Vec::new();
    for rel in String::from_utf8_lossy(&out.stdout).lines() {
        let path = root.join(rel);
        let Ok(text) = std::fs::read_to_string(&path) else {
            continue;
        };
        if !text.lines().take(4).any(|line| line == MARKER) {
            continue;
        }
        let dir = path.parent().expect("an index has a directory");
        for target in dead_links(dir, &text) {
            dead.push(format!("{rel} -> {target}"));
        }
    }
    assert!(
        dead.is_empty(),
        "generated indexes link to no file:\n  {}",
        dead.join("\n  ")
    );
}
